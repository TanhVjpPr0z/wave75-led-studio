import type { HidDeviceInfo } from '../protocols/types';

export interface UsbReportSummary {
  reportId: number;
  reportIdHex: string;
  itemCount: number;
  estimatedByteLength: number;
}

export interface UsbCollectionSummary {
  usagePage: number;
  usagePageHex: string;
  usage: number;
  usageHex: string;
  isVendorDefined: boolean;
  inputReports: UsbReportSummary[];
  outputReports: UsbReportSummary[];
  featureReports: UsbReportSummary[];
}

export interface UsbDiagnosticReport {
  capturedAt: string;
  userAgent: string;
  device: {
    productName: string;
    vendorId: number;
    productId: number;
    vendorIdHex: string;
    productIdHex: string;
    opened: boolean;
  };
  collections: UsbCollectionSummary[];
  recommendedControlInterface: {
    usagePageHex: string;
    usageHex: string;
    transport: 'output' | 'feature' | 'none';
    reportId: number;
    packetSize: number;
  } | null;
  safetyNote: string;
}

export function toHex(value: number, pad = 4): string {
  return `0x${value.toString(16).toUpperCase().padStart(pad, '0')}`;
}

export function bytesToHex(bytes: Uint8Array, maxBytes = 64): string {
  const slice = bytes.length > maxBytes ? bytes.subarray(0, maxBytes) : bytes;
  const parts: string[] = [];
  for (let i = 0; i < slice.length; i++) {
    parts.push(slice[i].toString(16).toUpperCase().padStart(2, '0'));
  }
  return parts.join(' ') + (bytes.length > maxBytes ? ' ...' : '');
}

function estimateReportBytes(report: HIDReportInfo): number {
  let totalBits = 0;
  for (const item of report.items ?? []) {
    const size = item.reportSize ?? 8;
    const count = item.reportCount ?? 1;
    totalBits += size * count;
  }
  return totalBits > 0 ? Math.ceil(totalBits / 8) : 64;
}

function summarizeReports(reports: HIDReportInfo[] | undefined): UsbReportSummary[] {
  return (reports ?? []).map((r) => ({
    reportId: r.reportId,
    reportIdHex: toHex(r.reportId, 2),
    itemCount: r.items?.length ?? 0,
    estimatedByteLength: estimateReportBytes(r),
  }));
}

export function extractUsbDiagnosticReport(device: HIDDevice): UsbDiagnosticReport {
  const collections: UsbCollectionSummary[] = (device.collections ?? []).map((c) => ({
    usagePage: c.usagePage,
    usagePageHex: toHex(c.usagePage, 4),
    usage: c.usage,
    usageHex: toHex(c.usage, 2),
    isVendorDefined: c.usagePage >= 0xff00,
    inputReports: summarizeReports(c.inputReports),
    outputReports: summarizeReports(c.outputReports),
    featureReports: summarizeReports(c.featureReports),
  }));

  const vendorCol = selectBestControlCollection(device);
  let recommended: UsbDiagnosticReport['recommendedControlInterface'] = null;
  if (vendorCol) {
    const outRep = vendorCol.outputReports?.[0];
    const featRep = vendorCol.featureReports?.[0];
    if (outRep) {
      recommended = {
        usagePageHex: toHex(vendorCol.usagePage, 4),
        usageHex: toHex(vendorCol.usage, 2),
        transport: 'output',
        reportId: outRep.reportId,
        packetSize: clampPacketSize(estimateReportBytes(outRep)),
      };
    } else if (featRep) {
      recommended = {
        usagePageHex: toHex(vendorCol.usagePage, 4),
        usageHex: toHex(vendorCol.usage, 2),
        transport: 'feature',
        reportId: featRep.reportId,
        packetSize: clampPacketSize(estimateReportBytes(featRep)),
      };
    }
  }

  return {
    capturedAt: new Date().toISOString(),
    userAgent: navigator.userAgent,
    device: {
      productName: device.productName || 'Unknown HID Device',
      vendorId: device.vendorId,
      productId: device.productId,
      vendorIdHex: toHex(device.vendorId, 4),
      productIdHex: toHex(device.productId, 4),
      opened: device.opened,
    },
    collections,
    recommendedControlInterface: recommended,
    safetyNote:
      'Read-only USB HID descriptor diagnostic report generated by WIN60HE LED Studio. Zero bytes were written to the keyboard.',
  };
}

function clampPacketSize(size: number): number {
  if (size >= 63 && size <= 64) return size;
  if (size >= 32 && size <= 64) return size;
  return 64;
}

export function selectBestControlCollection(device: HIDDevice): HIDCollectionInfo | null {
  const cols = device.collections ?? [];
  // Priority 1: Known AULA/Sayo vendor usagePage 0xFF1B with output/feature reports
  const ff1b = cols.find(
    (c) =>
      c.usagePage === 0xff1b &&
      ((c.outputReports?.length ?? 0) > 0 || (c.featureReports?.length ?? 0) > 0)
  );
  if (ff1b) return ff1b;

  // Priority 2: Any vendor-defined usagePage >= 0xFF00 with output reports
  const vendorOut = cols.find(
    (c) => c.usagePage >= 0xff00 && (c.outputReports?.length ?? 0) > 0
  );
  if (vendorOut) return vendorOut;

  // Priority 3: Any vendor-defined usagePage >= 0xFF00 with feature reports
  const vendorFeat = cols.find(
    (c) => c.usagePage >= 0xff00 && (c.featureReports?.length ?? 0) > 0
  );
  if (vendorFeat) return vendorFeat;

  // Fallback: any collection with usagePage >= 0xFF00
  return cols.find((c) => c.usagePage >= 0xff00) ?? null;
}

export function selectBestVendorDevice(devices: HIDDevice[]): HIDDevice | null {
  if (devices.length === 0) return null;

  // Score each HID interface returned by requestDevice()
  let bestDevice = devices[0];
  let bestScore = -1;

  for (const dev of devices) {
    let score = 0;
    if (dev.vendorId === 0x2e3c && dev.productId === 0xc365) score += 60;
    for (const c of dev.collections ?? []) {
      if (c.usagePage === 0xff1b && c.usage === 0x91) score += 100;
      else if (c.usagePage === 0xff1b) score += 80;
      else if (c.usagePage >= 0xff00) score += 50;
      if ((c.outputReports?.length ?? 0) > 0) score += 20;
      if ((c.featureReports?.length ?? 0) > 0) score += 15;
      // Penalize standard Boot Keyboard / Mouse / Consumer Control interfaces
      if (c.usagePage === 0x01 && (c.usage === 0x06 || c.usage === 0x02)) score -= 40;
      if (c.usagePage === 0x0c) score -= 25;
    }
    if (score > bestScore) {
      bestScore = score;
      bestDevice = dev;
    }
  }

  return bestDevice;
}

export function buildHidDeviceInfo(device: HIDDevice): HidDeviceInfo {
  const col = selectBestControlCollection(device) ?? device.collections?.[0];
  const outRep = col?.outputReports?.[0];
  const featRep = col?.featureReports?.[0];
  const transport: 'output' | 'feature' = outRep ? 'output' : 'feature';
  const packetSize = clampPacketSize(
    outRep ? estimateReportBytes(outRep) : featRep ? estimateReportBytes(featRep) : 64
  );

  return {
    vendorId: device.vendorId,
    productId: device.productId,
    vendorIdHex: toHex(device.vendorId, 4),
    productIdHex: toHex(device.productId, 4),
    productName: device.productName || 'AULA WIN60 Series',
    usagePage: col?.usagePage ?? 0xff1b,
    usagePageHex: toHex(col?.usagePage ?? 0xff1b, 4),
    usage: col?.usage ?? 0x91,
    usageHex: toHex(col?.usage ?? 0x91, 2),
    outputReportId: outRep?.reportId ?? 0x00,
    featureReportId: featRep?.reportId ?? 0x00,
    packetSize,
    transport,
  };
}

export function downloadUsbDiagnosticJson(report: UsbDiagnosticReport): void {
  const blob = new Blob([JSON.stringify(report, null, 2)], {
    type: 'application/json;charset=utf-8',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `usb-diagnostic-report-${report.device.vendorIdHex}-${report.device.productIdHex}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

