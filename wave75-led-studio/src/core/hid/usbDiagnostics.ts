import type { WaveDeviceInfo } from '../protocols/types';

export interface UsbReportSummary {
  reportId: number;
  reportIdHex: string;
  estimatedBytes: number;
}

export interface UsbCollectionSummary {
  usagePage: number;
  usagePageHex: string;
  usage: number;
  usageHex: string;
  isVendor: boolean;
  isQmkVia: boolean;
  inputReports: UsbReportSummary[];
  outputReports: UsbReportSummary[];
  featureReports: UsbReportSummary[];
}

export interface WaveUsbDiagnosticReport {
  capturedAt: string;
  userAgent: string;
  device: {
    productName: string;
    vendorId: number;
    productId: number;
    vendorIdHex: string;
    productIdHex: string;
    opened: boolean;
  };
  collections: UsbCollectionSummary[];
  detectedProtocol: 'pmo_native' | 'qmk_via' | 'unknown';
  safetyNote: string;
}

export function toHex(n: number, pad = 4): string {
  return `0x${n.toString(16).toUpperCase().padStart(pad, '0')}`;
}

export function bytesToHex(bytes: Uint8Array, limit = 32): string {
  const view = bytes.length > limit ? bytes.subarray(0, limit) : bytes;
  const out: string[] = [];
  for (let i = 0; i < view.length; i++) {
    out.push(view[i].toString(16).toUpperCase().padStart(2, '0'));
  }
  return out.join(' ') + (bytes.length > limit ? ` (+${bytes.length - limit}B)` : '');
}

function estimateBytes(rep: HIDReportInfo): number {
  let bits = 0;
  for (const item of rep.items ?? []) {
    bits += (item.reportSize ?? 8) * (item.reportCount ?? 1);
  }
  return bits > 0 ? Math.ceil(bits / 8) : 64;
}

function mapReports(reports?: HIDReportInfo[]): UsbReportSummary[] {
  return (reports ?? []).map((r) => ({
    reportId: r.reportId,
    reportIdHex: toHex(r.reportId, 2),
    estimatedBytes: estimateBytes(r),
  }));
}

export function extractWaveDiagnosticReport(device: HIDDevice): WaveUsbDiagnosticReport {
  const collections: UsbCollectionSummary[] = (device.collections ?? []).map((c) => ({
    usagePage: c.usagePage,
    usagePageHex: toHex(c.usagePage, 4),
    usage: c.usage,
    usageHex: toHex(c.usage, 2),
    isVendor: c.usagePage >= 0xff00,
    isQmkVia: c.usagePage === 0xff60 && c.usage === 0x61,
    inputReports: mapReports(c.inputReports),
    outputReports: mapReports(c.outputReports),
    featureReports: mapReports(c.featureReports),
  }));

  const hasQmk = collections.some((c) => c.isQmkVia);
  const isPmoNative =
    (device.vendorId === 0x36b0 && device.productId === 0x3009) ||
    collections.some((c) => c.isVendor && !c.isQmkVia && c.outputReports.length > 0);

  return {
    capturedAt: new Date().toISOString(),
    userAgent: navigator.userAgent,
    device: {
      productName: device.productName || 'PMO WAVE75 / RD75',
      vendorId: device.vendorId,
      productId: device.productId,
      vendorIdHex: toHex(device.vendorId, 4),
      productIdHex: toHex(device.productId, 4),
      opened: device.opened,
    },
    collections,
    detectedProtocol: isPmoNative ? 'pmo_native' : hasQmk ? 'qmk_via' : 'unknown',
    safetyNote:
      'Read-only USB HID descriptor diagnostic report generated by WAVE75 LED Studio. Zero bootloader or firmware flash commands exist in this application.',
  };
}

export function selectBestWaveDevice(
  devices: HIDDevice[],
  preferQmk = false
): HIDDevice | null {
  if (devices.length === 0) return null;
  let best = devices[0];
  let bestScore = -999;

  for (const dev of devices) {
    let score = 0;
    if (dev.vendorId === 0x36b0 && dev.productId === 0x3009) score += 80;
    for (const c of dev.collections ?? []) {
      const isQmk = c.usagePage === 0xff60 && c.usage === 0x61;
      if (preferQmk && isQmk) score += 120;
      else if (!preferQmk && c.usagePage >= 0xff00 && !isQmk) score += 100;
      else if (isQmk) score += 60;
      if ((c.outputReports?.length ?? 0) > 0) score += 25;
      if (c.usagePage === 0x01 && (c.usage === 0x06 || c.usage === 0x02)) score -= 50;
    }
    if (score > bestScore) {
      bestScore = score;
      best = dev;
    }
  }
  return best;
}

export function buildWaveDeviceInfo(
  device: HIDDevice,
  transportMode: WaveDeviceInfo['transportMode']
): WaveDeviceInfo {
  const vendorCol =
    (device.collections ?? []).find((c) =>
      transportMode === 'qmk_via'
        ? c.usagePage === 0xff60 && c.usage === 0x61
        : c.usagePage >= 0xff00 && (c.outputReports?.length ?? 0) > 0
    ) ?? device.collections?.[0];

  const outRep = vendorCol?.outputReports?.[0];
  return {
    vendorId: device.vendorId,
    productId: device.productId,
    vendorIdHex: toHex(device.vendorId, 4),
    productIdHex: toHex(device.productId, 4),
    productName: device.productName || 'PMO WAVE75',
    usagePage: vendorCol?.usagePage ?? (transportMode === 'qmk_via' ? 0xff60 : 0xff00),
    usagePageHex: toHex(vendorCol?.usagePage ?? (transportMode === 'qmk_via' ? 0xff60 : 0xff00), 4),
    usage: vendorCol?.usage ?? (transportMode === 'qmk_via' ? 0x61 : 0x01),
    usageHex: toHex(vendorCol?.usage ?? (transportMode === 'qmk_via' ? 0x61 : 0x01), 2),
    reportId: outRep?.reportId ?? 0x00,
    packetSize: transportMode === 'qmk_via' ? 32 : outRep ? Math.min(64, Math.max(32, estimateBytes(outRep))) : 64,
    transportMode,
  };
}

export function downloadWaveDiagnosticJson(report: WaveUsbDiagnosticReport): void {
  const blob = new Blob([JSON.stringify(report, null, 2)], {
    type: 'application/json;charset=utf-8',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `wave75-usb-report-${report.device.vendorIdHex}-${report.device.productIdHex}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

