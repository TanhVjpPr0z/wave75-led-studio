  const logoModeMap: Record<LogoSettings['effect'], number> = {
    rainbow: 1,
    neon_pulse: 2,
    breathing: 3,
    static: 4,
    off: 4,
  };
  const logoSwitch = logoOff ? 1 : 0;
  const logoMode = logoModeMap[logoSettings.effect] ?? 1;
  const logoBri = logoOff ? 0 : clamp(Math.round((logoSettings.brightness / 100) * 160), 10, 160);
  const logoSpdRev = clamp(4 - Math.round(((logoSettings.speed - 1) / 4) * 4), 0, 4);
  const logoMix = logoSettings.effect === 'rainbow' || logoSettings.effect === 'neon_pulse' ? 1 : 0;
  const logoR = clampByte(logoSettings.color.r);
  const logoG = clampByte(logoSettings.color.g);
  const logoB = clampByte(logoSettings.color.b);

  const safeSlug =
    effectName
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'custom';
  const filename = `wave75-driver-${safeSlug}.ps1`;
  const batFilename = `install-wave75-${safeSlug}.bat`;
